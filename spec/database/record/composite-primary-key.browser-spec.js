import Configuration from "../../../src/configuration.js"
import Project from "../../dummy/src/models/project.js"
import Record from "../../../src/database/record/index.js"
import RecordAttachmentsStore from "../../../src/database/record/attachments/store.js"
import Task from "../../dummy/src/models/task.js"
import {modelPrimaryKeyCacheKey} from "../../../src/utils/model-primary-key.js"

/** In-memory attachment driver for composite-key ownership coverage. */
class CompositePrimaryKeyAttachmentDriver {
  /** @type {Map<string, Buffer>} */
  contents = new Map()

  /**
   * @param {{attachmentId: string, input: {contentBuffer: Buffer}}} args - Attachment write arguments.
   * @returns {Promise<{storageKey: string}>} - Written storage identity.
   */
  async write({attachmentId, input}) {
    this.contents.set(attachmentId, input.contentBuffer)

    return {storageKey: attachmentId}
  }

  /**
   * @param {{storageKey: string}} args - Attachment read arguments.
   * @returns {Promise<Buffer>} - Stored attachment bytes.
   */
  async read({storageKey}) {
    const content = this.contents.get(storageKey)

    if (!content) throw new Error(`Missing attachment content: ${storageKey}`)

    return content
  }
}

/** Composite-key view of the dummy tasks table. */
class CompositePrimaryKeyTask extends Record {}

/** Composite-key view with uniqueness validation. */
class ValidatedCompositePrimaryKeyTask extends Record {}

/** Composite-key view whose id component is generated by the database. */
class GeneratedCompositePrimaryKeyTask extends Record {}

/** Composite-key view that rejects updates after persistence. */
class FailingAfterUpdateCompositePrimaryKeyTask extends Record {
  /**
   * Rejects the update after the record and attachment identities have changed.
   * @returns {Promise<void>} - Never resolves successfully.
   */
  async afterUpdate() {
    throw new Error("Composite update rejected after persistence")
  }
}

/** Attachment store that exposes any attempted fallback connection checkout. */
class SeparateConnectionRejectingAttachmentStore extends RecordAttachmentsStore {
  /**
   * Rejects fallback database checkout for transaction-owned identity migration.
   * @template T
   * @param {(db: import("../../../src/database/drivers/base.js").default) => Promise<T>} _callback - Unused fallback callback.
   * @param {import("../../../src/database/record/index.js").default} [_model] - Unused model.
   * @returns {Promise<T>} - Never resolves successfully.
   */
  async _withDb(_callback, _model) {
    throw new Error("Attachment identity migration checked out a separate connection")
  }
}

CompositePrimaryKeyTask.setTableName("tasks")
CompositePrimaryKeyTask.setPrimaryKey(["name", "project_id"])
CompositePrimaryKeyTask.hasOneAttachment("descriptionFile", {driver: CompositePrimaryKeyAttachmentDriver})
ValidatedCompositePrimaryKeyTask.setTableName("tasks")
ValidatedCompositePrimaryKeyTask.setPrimaryKey(["name", "project_id"])
ValidatedCompositePrimaryKeyTask.validates("name", {uniqueness: true})
GeneratedCompositePrimaryKeyTask.setTableName("tasks")
GeneratedCompositePrimaryKeyTask.setPrimaryKey(["id", "project_id"])
FailingAfterUpdateCompositePrimaryKeyTask.setTableName("tasks")
FailingAfterUpdateCompositePrimaryKeyTask.setPrimaryKey(["name", "project_id"])
FailingAfterUpdateCompositePrimaryKeyTask.hasOneAttachment("descriptionFile", {driver: CompositePrimaryKeyAttachmentDriver})

describe("Record - composite primary key", {tags: ["dummy"]}, () => {
  it("keeps scalar primary-key behavior unchanged", async () => {
    const project = await Project.create({name: "Scalar identity project"})
    const task = await Task.create({name: "Scalar identity task", project})

    expect(["number", "string"].includes(typeof task.id())).toBeTrue()
    expect((await Task.find(task.id()))?.id()).toEqual(task.id())
  })

  it("creates and finds a record by every composite key component", async () => {
    const project = await Project.create({name: "Composite identity project"})
    const task = await CompositePrimaryKeyTask.create({name: "Composite identity task", project_id: project.id()})

    expect(task.id()).toEqual({name: "Composite identity task", project_id: project.id()})

    const foundTask = await CompositePrimaryKeyTask.find({name: "Composite identity task", project_id: project.id()})

    expect(foundTask?.id()).toEqual({name: "Composite identity task", project_id: project.id()})
  })

  it("orders first and last by every composite key component", async () => {
    const firstProject = await Project.create({name: "Composite ordering first project"})
    const lastProject = await Project.create({name: "Composite ordering last project"})
    const sharedName = "Composite ordering task"

    await CompositePrimaryKeyTask.create({name: sharedName, project_id: lastProject.id()})
    await CompositePrimaryKeyTask.create({name: sharedName, project_id: firstProject.id()})

    const firstTask = await CompositePrimaryKeyTask.where({name: sharedName}).first()
    const lastTask = await CompositePrimaryKeyTask.where({name: sharedName}).last()

    expect(firstTask?.id()).toEqual({name: sharedName, project_id: firstProject.id()})
    expect(lastTask?.id()).toEqual({name: sharedName, project_id: lastProject.id()})
  })

  it("reloads a create from database-generated composite key components", async () => {
    const project = await Project.create({name: "Generated composite identity project"})
    const task = await GeneratedCompositePrimaryKeyTask.create({
      name: "Generated composite identity task",
      project_id: project.id()
    })
    const identity = task.id()

    if (typeof identity !== "object") throw new Error("Expected a composite identity")

    expect(identity.project_id).toEqual(project.id())
    expect(["number", "string"].includes(typeof identity.id)).toBeTrue()
    expect((await GeneratedCompositePrimaryKeyTask.find(identity))?.id()).toEqual(identity)
  })

  it("updates non-key attributes using the persisted composite identity", async () => {
    const project = await Project.create({name: "Composite non-key update project"})
    const task = await CompositePrimaryKeyTask.create({description: "Before", name: "Composite non-key update task", project_id: project.id()})

    await task.update({description: "After"})

    const foundTask = await CompositePrimaryKeyTask.find(task.id())

    expect(foundTask?.readAttribute("description")).toEqual("After")
  })

  it("locates a key-changing update by its persisted identity and reloads by its new identity", async () => {
    const originalProject = await Project.create({name: "Composite original project"})
    const replacementProject = await Project.create({name: "Composite replacement project"})
    const task = await CompositePrimaryKeyTask.create({name: "Composite original task", project_id: originalProject.id()})

    await task.update({name: "Composite renamed task", project_id: replacementProject.id()})

    expect(task.id()).toEqual({name: "Composite renamed task", project_id: replacementProject.id()})
    expect(await CompositePrimaryKeyTask.findBy({name: "Composite original task", project_id: originalProject.id()})).toBeNull()
    expect((await CompositePrimaryKeyTask.find(task.id()))?.id()).toEqual(task.id())
  })

  it("excludes the persisted composite identity from uniqueness checks while re-keying", async () => {
    const originalProject = await Project.create({name: "Composite validation original project"})
    const replacementProject = await Project.create({name: "Composite validation replacement project"})
    const task = await ValidatedCompositePrimaryKeyTask.create({
      name: "Composite validated task",
      project_id: originalProject.id()
    })

    await task.update({project_id: replacementProject.id()})

    expect(task.id()).toEqual({name: "Composite validated task", project_id: replacementProject.id()})
  })

  it("migrates attachment ownership when the composite identity changes", async () => {
    const project = await Project.create({name: "Composite attachment project"})
    const task = await CompositePrimaryKeyTask.create({name: "Composite attachment task", project_id: project.id()})

    await task.getAttachmentByName("descriptionFile").attach({
      content: "composite attachment",
      filename: "composite.txt"
    })
    await task.update({name: "Composite attachment renamed"})

    const attachment = await task.getAttachmentByName("descriptionFile").download()

    expect(attachment.filename()).toEqual("composite.txt")
    expect(attachment.content().toString()).toEqual("composite attachment")
  })

  it("rolls attachment ownership back when a later update callback rejects", async () => {
    const project = await Project.create({name: "Composite rollback project"})
    const task = await FailingAfterUpdateCompositePrimaryKeyTask.create({
      name: "Composite rollback task",
      project_id: project.id()
    })
    const originalIdentity = task.id()

    await task.getAttachmentByName("descriptionFile").attach({
      content: "rollback attachment",
      filename: "rollback.txt"
    })

    await expect(async () => {
      await task.update({name: "Composite rollback renamed"})
    }).toThrow("Composite update rejected after persistence")

    const originalTask = await FailingAfterUpdateCompositePrimaryKeyTask.find(originalIdentity)

    if (!originalTask) throw new Error("Expected the original composite record after rollback")
    expect(await FailingAfterUpdateCompositePrimaryKeyTask.findBy({
      name: "Composite rollback renamed",
      project_id: project.id()
    })).toBeNull()

    const attachment = await originalTask.getAttachmentByName("descriptionFile").download()

    if (!attachment) throw new Error("Expected attachment ownership to roll back with its record")
    expect(attachment.filename()).toEqual("rollback.txt")
    expect(attachment.content().toString()).toEqual("rollback attachment")
  })

  it("uses the record transaction connection when migrating attachment ownership", async () => {
    const project = await Project.create({name: "Composite migration connection project"})
    const task = await CompositePrimaryKeyTask.create({
      name: "Composite migration connection task",
      project_id: project.id()
    })
    const store = new SeparateConnectionRejectingAttachmentStore({
      configuration: Configuration.current(),
      databaseIdentifier: CompositePrimaryKeyTask.getDatabaseIdentifier()
    })

    await store.migrateRecordIdentity({
      connection: task.connection(),
      model: task,
      nextIdentity: {name: "Composite migration connection renamed", project_id: project.id()},
      previousIdentity: task.id()
    })
  })

  it("stores canonical composite attachment identities without a length limit", async () => {
    const project = await Project.create({name: "Long composite attachment project"})
    const task = await CompositePrimaryKeyTask.create({name: "x".repeat(255), project_id: project.id()})
    const canonicalIdentity = modelPrimaryKeyCacheKey(CompositePrimaryKeyTask.primaryKey(), task.id())

    expect(canonicalIdentity.length > 255).toBeTrue()

    await task.getAttachmentByName("descriptionFile").attach({
      content: "long composite attachment",
      filename: "long-composite.txt"
    })

    const attachmentTable = await CompositePrimaryKeyTask.connection().getTableByNameOrFail("velocious_attachments")
    const recordIdColumn = await attachmentTable.getColumnByNameOrFail("record_id")
    const recordIdMaxLength = recordIdColumn.getMaxLength()

    expect(typeof recordIdMaxLength === "number" && recordIdMaxLength > 0).toBeFalse()

    const attachment = await task.getAttachmentByName("descriptionFile").download()

    if (!attachment) throw new Error("Expected attachment for long composite identity")
    expect(attachment.filename()).toEqual("long-composite.txt")
    expect(attachment.content().toString()).toEqual("long composite attachment")
  })

  it("destroys a record using every composite key component", async () => {
    const project = await Project.create({name: "Composite destroy project"})
    const task = await CompositePrimaryKeyTask.create({name: "Composite destroy task", project_id: project.id()})
    const identity = task.id()

    await task.destroy()

    expect(await CompositePrimaryKeyTask.findBy(identity)).toBeNull()
  })

  it("rejects malformed composite identities", async () => {
    const invalidIdentities = [
      "Composite task",
      ["Composite task", 1],
      null,
      {name: "Composite task"},
      {name: "Composite task", project_id: 1, extra: true},
      {name: null, project_id: 1},
      {name: "Composite task", project_id: undefined}
    ]

    for (const identity of invalidIdentities) {
      await expect(async () => await CompositePrimaryKeyTask.find(identity)).toThrow(/composite primary key identity/u)
    }
  })
})
